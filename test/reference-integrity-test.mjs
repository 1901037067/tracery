import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { createReferenceStore } from '../server/reference-store.js';
import { createHistoryStore } from '../server/history-store.js';
import { revisionOf } from '../server/note-store.js';
fs.mkdirSync(path.resolve('dist'), { recursive: true });
const HOME = fs.mkdtempSync(path.resolve('dist/reference-integrity-')), ROOT = path.join(HOME, 'vault'); fs.mkdirSync(ROOT);
const put = (rel, text) => { const file = path.join(ROOT, rel); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
const get = rel => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const store = createReferenceStore({ home: HOME, history: createHistoryStore(HOME) });
for (const rel of ['图/a.png', '图/a b.png', '其他/a.png', '文档/a.pdf']) put(rel, 'BINARY-' + rel);
put('图/a.draw.json', '{"drawing":true}');
const content = '\uFEFF# 笔记\n![[图/a.png|320]]\n![](../图/a%20b.png "标题")\n[说明](../文档/a.pdf#page=2 "PDF")\n![角](<../图/a.png>)\n[id]: ../图/a.png "定义"\n`![[图/a.png]]`\n~~~md\n![[图/a.png]]\n~~~\n    ![[图/a.png]]\n[网页](https://example.test/a.png)';
put('笔记/主.md', content); put('其他/本地.md', '![[a.png]]');
let result = await store.rename(ROOT, '图/a.png', '新图/新.png');
assert.equal(result.references, 3); assert.equal(get('新图/新.draw.json'), '{"drawing":true}');
assert.ok(get('笔记/主.md').includes('![[新图/新.png|320]]'));
assert.ok(get('笔记/主.md').includes('<../新图/新.png>'));
assert.ok(get('笔记/主.md').includes('[id]: ../新图/新.png "定义"'));
assert.ok(get('笔记/主.md').includes('`![[图/a.png]]`')); assert.ok(get('笔记/主.md').includes('~~~md\n![[图/a.png]]\n~~~'));
assert.ok(get('笔记/主.md').startsWith('\uFEFF')); assert.equal(get('其他/本地.md'), '![[a.png]]');
put('移动/子.md', '![](../新图/新.png)\n[[../目标#节|别名]]'); put('目标.md', '# 目标');
put('外部.md', '![[移动/子#节|别名]]\n[[日记]]'); put('日记/x.md', '# x'); put('日记.md', '# 日记');
await store.rename(ROOT, '移动', '归档/移动');
assert.equal(get('归档/移动/子.md'), '![](../../新图/新.png)\n[[../../目标#节|别名]]');
assert.ok(get('外部.md').includes('![[归档/移动/子#节|别名]]'));
await store.rename(ROOT, '日记', '旧日记'); assert.ok(get('外部.md').includes('[[日记]]'));
await store.rename(ROOT, '图/a b.png', '图/c d.png'); assert.ok(get('笔记/主.md').includes('../图/c%20d.png "标题"'));
put('已存在.png', 'do not replace'); await assert.rejects(store.rename(ROOT, '新图/新.png', '已存在.png'), /已存在/); assert.equal(get('已存在.png'), 'do not replace');
put('缺图.md', '![[lost.png|218]]\n![说明](lost.png "保留标题")');
await store.relink(ROOT, '缺图.md', 'lost.png', '新图/新.png', revisionOf(get('缺图.md')));
assert.equal(get('缺图.md'), '![[新图/新.png|218]]\n![说明](新图/新.png "保留标题")');
await assert.rejects(store.relink(ROOT, '缺图.md', 'lost.png', '新图/新.png', 'stale'), /已变化/);
console.log('PASS 附件/目录移动改名、同名消歧、源文件相对路径、别名宽度锚点标题/BOM/代码保留、绘图旁车、冲突拒绝及重新关联');
put('回退.md', '![[新图/新.png]]'); const before = get('回退.md');
const failing = createReferenceStore({ home: HOME, fault: async stage => { if (stage === 'written') throw Error('injected write failure'); } });
await assert.rejects(failing.rename(ROOT, '新图/新.png', '新图/失败.png'), /injected/);
assert.equal(get('回退.md'), before); assert.equal(get('新图/新.png'), 'BINARY-图/a.png'); assert.equal(fs.existsSync(path.join(ROOT, '新图/失败.png')), false);
console.log('PASS 多文件引用写入失败后回退文件路径与正文');
const fixture = path.join(HOME, 'crash.mjs'), module = pathToFileURL(path.resolve('server/reference-store.js')).href;
fs.writeFileSync(fixture, `import {createReferenceStore} from ${JSON.stringify(module)};await createReferenceStore({home:process.env.FIXTURE_HOME,fault:async(stage)=>{if(stage==='written'){process.send({paused:true});await new Promise(()=>{});}}}).rename(process.env.FIXTURE_ROOT,'新图/新.png','新图/中止.png');`);
const child = spawn(process.execPath, [fixture], { env: { ...process.env, FIXTURE_HOME: HOME, FIXTURE_ROOT: ROOT }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe', 'ipc'] });
let trace = ''; child.stderr.on('data', data => trace += data);
await new Promise((resolve, reject) => { child.once('message', resolve); child.once('exit', () => reject(Error(trace || 'child exited early'))); });
const exited = new Promise(resolve => child.once('exit', resolve)); child.kill('SIGKILL'); await exited;
const warnings = await store.recover(ROOT); assert.ok(warnings.some(text => text.includes('已回退')));
assert.equal(get('新图/新.png'), 'BINARY-图/a.png'); assert.equal(get('回退.md'), before);
assert.equal(fs.existsSync(path.join(ROOT, '新图/中止.png')), false);
console.log('PASS 进程中止后从事务日志恢复，不覆盖不匹配正文');
// 第二个移动（绘图旁车）遇到外部新目标时，第一个已完成移动仍应回退。
put('竞态.md', '![[新图/新.png]]');
const colliding = createReferenceStore({ home: HOME, fault: async (stage, i) => {
  if (stage === 'moving' && i === 1) put('新图/冲突.draw.json', 'external drawing');
} });
await assert.rejects(colliding.rename(ROOT, '新图/新.png', '新图/冲突.png'), /目标路径已存在/);
assert.equal(get('新图/冲突.draw.json'), 'external drawing');
assert.equal(get('新图/新.draw.json'), '{"drawing":true}');
assert.equal(get('新图/新.png'), 'BINARY-图/a.png');
assert.equal(get('竞态.md'), '![[新图/新.png]]');
assert.equal(fs.existsSync(path.join(ROOT, '新图/冲突.png')), false);
await store.rename(ROOT, '新图/新.png', '新图/新.jpg');
assert.equal(get('新图/新.draw.json'), '{"drawing":true}');
await store.rename(ROOT, '新图/新.jpg', '新图/新.png');
console.log('PASS 旁车目标竞态保留外部文件并回退已移动附件；同名换扩展名保留旁车');
for (const stop of ['moving', 'moved-entry']) {
  fs.writeFileSync(fixture, `import {createReferenceStore} from ${JSON.stringify(module)};await createReferenceStore({home:process.env.FIXTURE_HOME,fault:async(stage,i)=>{if(stage===${JSON.stringify(stop)}&&i===1){process.send({paused:true});await new Promise(()=>{});}}}).rename(process.env.FIXTURE_ROOT,'新图/新.png','新图/中止.png');`);
  const processUnderTest = spawn(process.execPath, [fixture], { env: { ...process.env, FIXTURE_HOME: HOME, FIXTURE_ROOT: ROOT }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe', 'ipc'] });
  let stderr = ''; processUnderTest.stderr.on('data', data => stderr += data);
  await new Promise((resolve, reject) => { processUnderTest.once('message', resolve); processUnderTest.once('exit', () => reject(Error(stderr || 'child exited early'))); });
  const closed = new Promise(resolve => processUnderTest.once('exit', resolve)); processUnderTest.kill('SIGKILL'); await closed;
  assert.ok((await store.recover(ROOT)).some(text => text.includes('已回退')));
  assert.equal(get('新图/新.png'), 'BINARY-图/a.png'); assert.equal(get('新图/新.draw.json'), '{"drawing":true}');
  assert.equal(get('竞态.md'), '![[新图/新.png]]');
  assert.equal(fs.existsSync(path.join(ROOT, '新图/中止.png')), false);
  assert.equal(fs.existsSync(path.join(ROOT, '新图/中止.draw.json')), false);
}
// 回退时不覆盖外部重建的原路径，并允许解决冲突后再次恢复。
const external = createReferenceStore({ home: HOME, fault: async stage => {
  if (stage === 'moved') { put('新图/新.png', 'external original'); throw Error('injected collision'); }
} });
await assert.rejects(external.rename(ROOT, '新图/新.png', '新图/保留.png'), /自动回退未完成/);
assert.equal(get('新图/新.png'), 'external original'); assert.equal(get('新图/保留.png'), 'BINARY-图/a.png');
fs.renameSync(path.join(ROOT, '新图/新.png'), path.join(ROOT, '新图/外部副本.png'));
assert.ok((await store.recover(ROOT)).some(text => text.includes('已回退')));
assert.equal(get('新图/新.png'), 'BINARY-图/a.png'); assert.equal(get('新图/外部副本.png'), 'external original');
assert.deepEqual(await store.recover(ROOT), []);
console.log('PASS 分项移动前后强停恢复、外部冲突保留和再次恢复幂等');
